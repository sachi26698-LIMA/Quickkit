import { readFile } from "node:fs/promises";
import { test, expect } from "@playwright/test";

/**
 * Barcode Scanner in a real browser.
 *
 * Three things are proven here that jsdom cannot prove:
 *  - a PNG produced by the generator is decoded by the scanner's on-device
 *    decoder (no camera, no upload);
 *  - a denied camera permission produces a described error, not a broken view;
 *  - a granted camera starts only on click, stops on demand and has its tracks
 *    ended when the tool is left.
 *
 * The camera is Chromium's fake capture device; that is real browser media
 * plumbing, not a claim that a physical camera was tested.
 */
test("decodes a PNG generated by the Barcode Studio on this device", async ({
  page,
}) => {
  await page.goto("/tools/barcode-generator");
  await page.getByLabel("Barcode data").fill("E2E-UPLOAD-42");
  const [download] = await Promise.all([
    page.waitForEvent("download"),
    page
      .locator("#bc-panel-generate")
      .getByRole("button", { name: /^PNG$/ })
      .click(),
  ]);
  const png = await download.path();
  expect(png).toBeTruthy();

  await page.goto("/tools/barcode-scanner");
  // Playwright's temp download path has no extension, and the scanner refuses a
  // file whose type it cannot establish, so upload the bytes with a real name.
  const bytes = await readFile(png!);
  await page.getByRole("tab", { name: "Image upload" }).click();
  await page.locator("#barcode-image-input").setInputFiles({
    name: "generated-barcode.png",
    mimeType: "image/png",
    buffer: bytes,
  });

  await expect(page.getByText("E2E-UPLOAD-42").first()).toBeVisible({
    timeout: 20_000,
  });
  await expect(
    page.getByText(/on this device|decoded on this device/i).first(),
  ).toBeVisible();

  // The successful decode is recorded locally and can be cleared.
  const history = page.locator('section[aria-labelledby="history-heading"]');
  await expect(history).toContainText("E2E-UPLOAD-42");
  await page.getByRole("button", { name: /Clear history/i }).click();
  await expect(history).not.toContainText("E2E-UPLOAD-42");
});

test("explains a denied camera permission instead of failing silently", async ({
  page,
}) => {
  await page.addInitScript(() => {
    const denied = Object.assign(new Error("denied"), {
      name: "NotAllowedError",
    });
    Object.defineProperty(navigator, "mediaDevices", {
      configurable: true,
      value: {
        getUserMedia: () => Promise.reject(denied),
        enumerateDevices: async () => [],
      },
    });
  });

  await page.goto("/tools/barcode-scanner");
  await page.getByRole("button", { name: "Start camera" }).click();

  const alert = page.locator("#panel-camera").getByRole("alert");
  await expect(alert).toBeVisible({ timeout: 10_000 });
  await expect(alert).toContainText(/permission|blocked|denied/i);
  await expect(page.getByText("Camera off")).toBeVisible();
});

test.describe("mobile layout", () => {
  test.use({ viewport: { width: 360, height: 780 } });

  test("never overflows horizontally and keeps the tabs usable", async ({
    page,
  }) => {
    await page.goto("/tools/barcode-scanner");
    const overflow = await page.evaluate(
      () => document.documentElement.scrollWidth - window.innerWidth,
    );
    expect(overflow).toBeLessThanOrEqual(0);

    const cameraTab = page.getByRole("tab", { name: "Camera" });
    const box = await cameraTab.boundingBox();
    expect(box!.height).toBeGreaterThanOrEqual(38);
    expect(box!.width).toBeGreaterThanOrEqual(80);

    await page.getByRole("tab", { name: "Image upload" }).click();
    await expect(
      page.getByText(/Choose images or drop them here/i),
    ).toBeVisible();
  });
});
