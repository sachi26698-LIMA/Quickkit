/** Backwards-compatible alias — the library *is* the template list now. */
export const QR_TEMPLATES = QR_TEMPLATE_LIBRARY;

export const templateById = (id: string) =>
  QR_TEMPLATE_LIBRARY.find((template) => template.id === id);

export const categoryLabel = (id: QrTemplateCategory) =>
  TEMPLATE_CATEGORIES.find((category) => category.id === id)?.label ?? id;

/** Case-insensitive search across name, blurb and category label. */
export function searchTemplates(
  templates: QrTemplate[],
  query: string,
  category: QrTemplateCategory | "all" | "custom",
): QrTemplate[] {
  const q = query.trim().toLowerCase();
  return templates.filter((template) => {
    if (category === "custom") {
      if (!template.custom) return false;
    } else if (category !== "all" && template.category !== category) {
      return false;
    }
    if (!q) return true;
    return (
      template.name.toLowerCase().includes(q) ||
      template.blurb.toLowerCase().includes(q) ||
      (template.label ?? "").toLowerCase().includes(q) ||
      categoryLabel(template.category).toLowerCase().includes(q)
    );
  });
}
