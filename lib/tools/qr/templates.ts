export type QrTemplate = {
  id: string;
  name: string;
  blurb: string;
  category: QrTemplateCategory;
  design: Partial<QrDesign>;
  /** Suggested caption — pre-fills the PDF caption when applied. */
  label?: string;
  /** Suggested print layout id (layout PDFs land in the export phase). */
  layout?: string;
  /** Suggested printed width of the code, in millimetres. */
  printMm?: number;
  /** True for user-saved templates (kept in this browser). */
  custom?: boolean;
};

/* ------------------------------------------------------------- fill helpers */

const solid = (base: string): QrFill => ({
  kind: "solid",
  base,
  accent: base,
  angle: 0,
});
const lin = (base: string, accent: string, angle = 135): QrFill => ({
  kind: "linear",
  base,
  accent,
  angle,
});
const rad = (base: string, accent: string): QrFill => ({
  kind: "radial",
  base,
  accent,
  angle: 0,
});
const logo = (
  scale: number,
  shape: QrLogoSettings["shape"] = "rounded",
  offsetX = 0,
  offsetY = 0,
): QrLogoSettings => ({
  scale,
  offsetX,
  offsetY,
  padding: 0.6,
  shape,
  halo: true,
  bg: null,
});

