"use client";
import { useEffect, useRef } from "react";

/**
 * Scroll-reveal wrapper. Content is visible by default (SSR/no-JS safe);
 * with JS, below-the-fold blocks start hidden (.reveal-init) and fade/slide
 * in once. All motion is disabled under prefers-reduced-motion via CSS.
 */
export default function Reveal({
  children,
  className = "",
}: {
  children: React.ReactNode;
  className?: string;
}) {
  const ref = useRef<HTMLDivElement>(null);
  useEffect(() => {
    const el = ref.current;
    if (!el) return;
    if (
      !("IntersectionObserver" in window) ||
      window.matchMedia("(prefers-reduced-motion: reduce)").matches
    ) {
      return;
    }
    if (el.getBoundingClientRect().top < window.innerHeight) return;
    el.classList.add("reveal-init");
    const observer = new IntersectionObserver(
      (entries) => {
        for (const entry of entries) {
          if (entry.isIntersecting) {
            entry.target.classList.add("is-visible");
            observer.unobserve(entry.target);
          }
        }
      },
      { threshold: 0.1 },
    );
    observer.observe(el);
    return () => observer.disconnect();
  }, []);
  return (
    <div ref={ref} className={`reveal ${className}`}>
      {children}
    </div>
  );
}
